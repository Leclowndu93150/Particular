def sprite(rows, size):
    out = np.zeros((size, size, 4), np.uint8)
    h, w = len(rows), max(len(r) for r in rows)
    oy, ox = (size - h) // 2, (size - w) // 2
    for y, row in enumerate(rows):
        for x, key in enumerate(row):
            if key != '.':
                out[oy + y, ox + x, :3] = SNOW[int(key)]
                out[oy + y, ox + x, 3] = 255
    return out


def build():
    files = {}
    for i, rows in enumerate(PUFFS):
        files[f'snow_puff_{i}.png'] = sprite(rows, PUFF_SIZE)
    for i, rows in enumerate(FLECKS):
        files[f'snow_fleck_{i}.png'] = sprite(rows, FLECK_SIZE)
    return files


def main():
    files = build()
    targets = [Path(sys.argv[1])] if len(sys.argv) > 1 else [ROOT / 'versions' / v / PARTICLE_DIR for v in VERSIONS]
    for target in targets:
        target.mkdir(parents=True, exist_ok=True)
        for name, img in files.items():
            Image.fromarray(img, 'RGBA').save(target / name)


if __name__ == '__main__':
    main()
